let currentLang = localStorage.getItem("plantai_lang") || "en";

function applyLang(lang) {
  currentLang = lang;
  localStorage.setItem("plantai_lang", lang);
  const dict = I18N[lang];

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    const key = el.getAttribute("data-i18n-ph");
    if (dict[key]) el.setAttribute("placeholder", dict[key]);
  });

  document.getElementById("langEnBtn").classList.toggle("on", lang === "en");
  document.getElementById("langArBtn").classList.toggle("on", lang === "ar");
}

function setLang(lang) {
  applyLang(lang);
  if (window.onLangChange) window.onLangChange(lang);
}

